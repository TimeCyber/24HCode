#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const dir = path.dirname(fileURLToPath(import.meta.url));
const code = (process.argv[2] || "").trim().toUpperCase();
const apiRoot = (process.argv[3] || "https://mcp-x.com/prod-api").replace(/\/+$/, "").replace(/\/codeassist$/, "");
if (code.length < 4) {
  console.error("Usage: node pair-claim.mjs <pair-code> [api-root]");
  process.exit(2);
}
const response = await fetch(`${apiRoot}/codeassist/pair/claim`, {
  method: "POST",
  headers: { "content-type": "application/json; charset=utf-8" },
  body: JSON.stringify({ code, deviceName: process.env.COMPUTERNAME || "PC Agent" }),
});
const result = await response.json();
if (!response.ok || result.error || !result.deviceToken) {
  console.error(`Pairing failed (${response.status}): ${result.error || "response did not contain deviceToken"}`);
  process.exit(1);
}
const relayUrl = `${apiRoot}/codeassist`;
const env = [
  "# Generated by pair-claim.mjs; do not commit",
  `CODEASSIST_SERVER_URL=${relayUrl}`,
  `CODEASSIST_TOKEN=${result.deviceToken}`,
  `CODEASSIST_DEVICE_ID=${result.deviceId || ""}`,
  `CODEASSIST_USER_ID=${result.userId || ""}`,
  `CODEASSIST_DEVICE_NAME=${result.deviceName || ""}`,
  "",
].join("\n");
fs.writeFileSync(path.join(dir, ".codeassist-device.env"), env, { encoding: "utf8", mode: 0o600 });
console.log(`Paired successfully. Credentials saved to ${path.join(dir, ".codeassist-device.env")}`);
console.log(`Relay: ${relayUrl}`);
